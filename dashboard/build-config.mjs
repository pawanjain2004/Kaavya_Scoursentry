import { writeFileSync, existsSync, readFileSync } from "fs";
import { fileURLToPath } from "url";
import { dirname, join } from "path";

const root = dirname(fileURLToPath(import.meta.url));

// Load local .env if present (Vercel injects env vars itself)
const envPath = join(root, ".env");
if (existsSync(envPath)) {
  for (const line of readFileSync(envPath, "utf8").split("\n")) {
    const t = line.trim();
    if (!t || t.startsWith("#")) continue;
    const i = t.indexOf("=");
    if (i < 0) continue;
    const key = t.slice(0, i).trim();
    let val = t.slice(i + 1).trim();
    if ((val.startsWith('"') && val.endsWith('"')) || (val.startsWith("'") && val.endsWith("'"))) {
      val = val.slice(1, -1);
    }
    if (process.env[key] === undefined) process.env[key] = val;
  }
}

function req(name) {
  const v = process.env[name];
  if (!v || v.startsWith("YOUR_")) {
    throw new Error(`Missing env var: ${name}. Set it in .env (local) or Vercel Environment Variables.`);
  }
  return v;
}

const config = `// AUTO-GENERATED by build-config.mjs — do not edit by hand.
export const firebaseConfig = {
  apiKey: ${JSON.stringify(req("FIREBASE_API_KEY"))},
  authDomain: ${JSON.stringify(req("FIREBASE_AUTH_DOMAIN"))},
  databaseURL: ${JSON.stringify(req("FIREBASE_DATABASE_URL"))},
  projectId: ${JSON.stringify(req("FIREBASE_PROJECT_ID"))},
  storageBucket: ${JSON.stringify(req("FIREBASE_STORAGE_BUCKET"))},
  messagingSenderId: ${JSON.stringify(process.env.FIREBASE_MESSAGING_SENDER_ID || "")},
  appId: ${JSON.stringify(req("FIREBASE_APP_ID"))},
  measurementId: ${JSON.stringify(process.env.FIREBASE_MEASUREMENT_ID || "")},
};

export const DEVICE_ID = ${JSON.stringify(process.env.DEVICE_ID || "pier-01")};
export const HISTORY_POINTS = ${Number(process.env.HISTORY_POINTS || 360)};
export const OFFLINE_AFTER_MS = ${Number(process.env.OFFLINE_AFTER_MS || 15000)};
`;

writeFileSync(join(root, "firebase-config.js"), config);
console.log("Wrote firebase-config.js from environment variables.");
